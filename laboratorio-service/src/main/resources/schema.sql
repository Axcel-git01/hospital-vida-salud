CREATE TABLE IF NOT EXISTS solicitud_laboratorio (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(20) NOT NULL UNIQUE,
    paciente_id BIGINT NOT NULL,
    atencion_id BIGINT NOT NULL,
    tipo_examen VARCHAR(60) NOT NULL,
    estado VARCHAR(15) NOT NULL,
    resultado_ficticio VARCHAR(200),
    fecha_solicitud TIMESTAMP NOT NULL,
    fecha_actualizacion TIMESTAMP NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_solicitud_atencion ON solicitud_laboratorio(atencion_id);
CREATE INDEX IF NOT EXISTS idx_solicitud_paciente ON solicitud_laboratorio(paciente_id);
